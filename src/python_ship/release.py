"""Plan unique production images and assemble Docker-only releases."""

from __future__ import annotations

from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import tempfile
from typing import Any

from . import __version__
from .compose import render
from .config import ConfigError, ShipConfig, command_text

TAG_PATTERN = r"[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}"


def plan_images(model: dict[str, Any], tag: str) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Give identical build definitions one image tag, one build owner and one archive."""
    planned = deepcopy(model)
    services = planned["services"]
    groups: dict[str, list[str]] = {}
    for name, service in services.items():
        if "build" in service:
            signature = json.dumps(service["build"], sort_keys=True, separators=(",", ":"))
            groups.setdefault(signature, []).append(name)
    images = []
    aliases = {}
    for members in groups.values():
        members = sorted(members)
        # The app owns its group; processes share its image.
        owner = next((name for name in members if not services[name].get("stop_grace_period")), members[0])
        image = f"{planned['name']}-{owner}:{tag}"
        for name in members:
            old_image = services[name].get("image")
            if old_image:
                aliases[old_image] = image
            services[name]["image"] = image
        images.append({"image": image, "owner": owner, "services": members})
    for service in services.values():
        if "build" not in service and service.get("image") in aliases:
            service["image"] = aliases[service["image"]]
    # Processes reuse the app's image without building it; list every service that runs each image.
    for entry in images:
        entry["services"] = sorted(name for name, service in services.items() if service.get("image") == entry["image"])
    return planned, sorted(images, key=lambda entry: entry["owner"])


def _run(command: list[str], root: Path) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(command, cwd=root, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise ConfigError(f"`{' '.join(command[:3])}` failed: {result.stderr.strip() or result.stdout.strip()}")
    return result


def release_model(model: dict[str, Any]) -> dict[str, Any]:
    """The production model with every build: removed and .env as the required env file."""
    release = deepcopy(model)
    for service in release["services"].values():
        service.pop("build", None)
        for env_file in service.get("env_file", []):
            if isinstance(env_file, dict) and env_file.get("path") == ".env.production":
                env_file["path"] = ".env"
                env_file["required"] = True
    return release


def deploy_script(config: ShipConfig, model: dict[str, Any]) -> str:
    """Start infrastructure, wait for it, then run each deploy command once in a fresh app container."""
    app = config.app_service
    infrastructure = sorted(set(model["services"]) - {app, *config.processes})
    lines = [
        "#!/bin/sh",
        "# Generated by python-ship. Runs once per deploy, before `docker compose up -d`.",
        "set -eu",
        'cd "$(dirname "$0")"',
    ]
    if infrastructure:
        lines.append("docker compose up -d --wait " + " ".join(map(shlex.quote, infrastructure)))
    for command in config.deploy_commands:
        lines.append(f"echo {shlex.quote('ship: ' + command_text(command))}")
        if isinstance(command, str):
            lines.append(f"docker compose run --rm --no-deps {shlex.quote(app)} sh -c {shlex.quote(command)}")
        else:
            lines.append(f"docker compose run --rm --no-deps {shlex.quote(app)} {shlex.join(command)}")
    return "\n".join(lines) + "\n"


def _git_commit(root: Path) -> str | None:
    try:
        result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, capture_output=True, text=True, check=False)
    except OSError:
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def assemble_release(root: Path, config: ShipConfig, model: dict[str, Any], tag: str) -> Path:
    """Export every image and publish the artifact only after every step succeeds."""
    source_env = root / ".env.production"
    if not source_env.is_file():
        raise ConfigError("ship release requires .env.production, even when no selected service needs credentials.")
    parent = root / "dist" / "ship"
    parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=".release-", dir=parent))
    destination = parent / tag
    try:
        if os.name != "nt":
            stage.chmod(0o700)
        images_dir = stage / "images"
        images_dir.mkdir()
        compose = release_model(model)
        (stage / "docker-compose.yml").write_text(render(compose), encoding="utf-8")
        shutil.copyfile(source_env, stage / ".env")
        if os.name != "nt":
            (stage / ".env").chmod(0o600)
        by_image: dict[str, list[str]] = {}
        for name, service in compose["services"].items():
            image = service.get("image")
            if not isinstance(image, str) or not image:
                raise ConfigError(f"Release service {name!r} has no image.")
            by_image.setdefault(image, []).append(name)
        images = []
        for image, members in sorted(by_image.items()):
            if subprocess.run(["docker", "image", "inspect", image], cwd=root, capture_output=True).returncode != 0:
                _run(["docker", "pull", image], root)
            archive = f"images/{sorted(members)[0]}.tar"
            _run(["docker", "save", "-o", str(stage / archive), image], root)
            images.append({"image": image, "file": archive, "sha256": _sha256(stage / archive), "services": sorted(members)})
        if config.deploy_commands:
            script = stage / "deploy-commands.sh"
            script.write_text(deploy_script(config, compose), encoding="utf-8", newline="\n")
            if os.name != "nt":
                script.chmod(0o700)
        instructions = [
            f"# Release {tag}", "",
            "Built by python-ship. From this directory, on a machine with Docker and Compose v2:", "",
            "```sh",
            *[f"docker load -i {entry['file']}" for entry in images],
            *(["sh deploy-commands.sh"] if config.deploy_commands else []),
            "docker compose up -d",
            "```", "",
            "`.env` holds production secrets; keep this directory private.", "",
        ]
        (stage / "README.md").write_text("\n".join(instructions), encoding="utf-8")
        manifest = {
            "tag": tag,
            "ship": {"package": "python-ship", "version": __version__},
            "git_commit": _git_commit(root),
            "images": images,
        }
        (stage / "release.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        if destination.is_symlink():
            raise ConfigError(f"Release destination {destination} is a symlink; remove it before retrying.")
        if destination.exists():
            shutil.rmtree(destination)
        stage.replace(destination)
        return destination
    finally:
        if stage.exists():
            shutil.rmtree(stage)
